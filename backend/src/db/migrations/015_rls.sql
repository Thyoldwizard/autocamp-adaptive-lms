-- ── instructor_cohorts ──────────────────────────────────────────────────────
-- Instructors can see their own cohort assignments. Only service_role
-- can manage the mapping.

CREATE POLICY "instructor: select own cohorts"
  ON instructor_cohorts FOR SELECT
  USING (instructor_id = auth.uid());

