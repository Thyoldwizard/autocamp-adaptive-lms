-- 015_rls.sql
-- Row-Level Security (defense in depth).
--
-- The backend uses the service_role key, which BYPASSES RLS — the app is
-- completely unaffected by this migration. RLS blocks direct PostgREST
-- access via user JWTs, preventing a learner from reading another learner's
-- rows even if they craft a valid JWT and query Supabase directly.
--
-- Pattern for learner-owned tables:
--   USING (learner_id IN (SELECT id FROM learners WHERE user_id = auth.uid()))
-- auth.uid() is the JWT `sub` claim; user_id is the FK to auth.users.
--
-- Catalog tables (skills, modules) are intentionally left without RLS —
-- they are already read-only for anon/authenticated and contain no PII.

-- ── Enable RLS on every learner-owned / sensitive table ─────────────────────

ALTER TABLE learners           ENABLE ROW LEVEL SECURITY;
ALTER TABLE skill_state        ENABLE ROW LEVEL SECURITY;
ALTER TABLE progress           ENABLE ROW LEVEL SECURITY;
ALTER TABLE struggle_signals   ENABLE ROW LEVEL SECURITY;
ALTER TABLE outcomes           ENABLE ROW LEVEL SECURITY;
ALTER TABLE companion_messages ENABLE ROW LEVEL SECURITY;
ALTER TABLE checkin_sessions   ENABLE ROW LEVEL SECURITY;
ALTER TABLE profiles           ENABLE ROW LEVEL SECURITY;
ALTER TABLE instructor_cohorts ENABLE ROW LEVEL SECURITY;
ALTER TABLE rules_config       ENABLE ROW LEVEL SECURITY;

-- ── learners ────────────────────────────────────────────────────────────────
-- SELECT and UPDATE own row only. INSERT is service_role only (signup flow).

CREATE POLICY "learner: select own row"
  ON learners FOR SELECT
  USING (user_id = auth.uid());

CREATE POLICY "learner: update own row"
  ON learners FOR UPDATE
  USING (user_id = auth.uid());

-- ── skill_state ─────────────────────────────────────────────────────────────

CREATE POLICY "learner: full access to own skill_state"
  ON skill_state FOR ALL
  USING (learner_id IN (SELECT id FROM learners WHERE user_id = auth.uid()));

-- ── progress ────────────────────────────────────────────────────────────────

CREATE POLICY "learner: full access to own progress"
