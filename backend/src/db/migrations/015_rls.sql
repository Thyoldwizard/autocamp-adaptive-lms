-- ── struggle_signals ────────────────────────────────────────────────────────
-- SELECT only for learners. INSERT/UPDATE/DELETE stays service_role only —
-- signals are generated by the backend, never by the learner directly.

CREATE POLICY "learner: select own struggle_signals"
  ON struggle_signals FOR SELECT
  USING (learner_id IN (SELECT id FROM learners WHERE user_id = auth.uid()));

